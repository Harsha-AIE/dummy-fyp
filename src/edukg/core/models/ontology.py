from __future__ import annotations

from uuid import UUID

from pydantic import Field

from edukg.core.models.common import ConfidenceScore, Identifiable, Timestamped
from edukg.core.models.enums import OntologyExtensionKind, Subject


class OntologyClass(Identifiable, Timestamped):
    """A concept class in the ontology (core or domain-specific)."""

    name: str = Field(min_length=1)
    subject: Subject
    parent_class_id: UUID | None = None
    description: str | None = None
    aliases: list[str] = Field(default_factory=list)
    is_core: bool = Field(default=False, description="True for core ontology classes shared across subjects")
    version: str = Field(default="1.0.0")


class OntologyRelation(Identifiable, Timestamped):
    """A typed predicate with domain/range constraints."""

    name: str = Field(min_length=1)
    subject: Subject
    domain_class_id: UUID = Field(description="Allowed subject-entity OntologyClass")
    range_class_id: UUID = Field(description="Allowed object-entity OntologyClass")
    is_symmetric: bool = Field(default=False)
    is_transitive: bool = Field(default=False)
    description: str | None = None
    version: str = Field(default="1.0.0")


class OntologyExtension(Identifiable, Timestamped):
    """A proposed addition to the ontology, generated by the LLM, pending review."""

    kind: OntologyExtensionKind
    subject: Subject
    proposed_name: str = Field(min_length=1)
    proposed_parent_class_id: UUID | None = None
    proposed_domain_class_id: UUID | None = None
    proposed_range_class_id: UUID | None = None
    proposed_aliases: list[str] = Field(default_factory=list)
    proposed_description: str | None = None
    justification: str = Field(min_length=1, description="LLM-provided rationale, shown to the reviewer")
    confidence: ConfidenceScore
    source_document_ids: list[UUID] = Field(default_factory=list)
    generator_model: str = Field(min_length=1)
    raw_llm_response: str | None = Field(default=None, description="Stored for audit/debugging only")
